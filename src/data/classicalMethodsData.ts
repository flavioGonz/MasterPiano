export type ClassicalBookId = 'hanon' | 'czerny' | 'suzuki';

export interface MethodNote {
  note: string; // e.g. 'C4'
  duration: string; // '8n', '4n', '2n', '1n'
  fingering: number; // 1 (pulgar), 2 (índice), 3 (medio), 4 (anular), 5 (meñique)
  hand: 'right' | 'left';
  measure?: number;
  articulation?: 'legato' | 'staccato' | 'accent' | 'normal';
  displayLabel?: string;
}

export interface ClassicalExercise {
  id: string;
  bookId: ClassicalBookId;
  exerciseNumber: number | string;
  title: string;
  subtitle: string;
  difficulty: 'Principiante' | 'Intermedio' | 'Avanzado';
  recommendedBpm: number;
  timeSignature: string; // '4/4', '3/4', '2/4'
  keySignature: string;
  focusTechnique: string;
  maestroAdvice: string;
  historicalNote: string;
  rightHandNotes: MethodNote[];
  leftHandNotes: MethodNote[];
}

